#!/usr/bin/env python3
"""PreToolUse: blocks (exit 2) commands that break the project's fixed rules.
Reads the hook JSON on stdin; looks at tool_input.command. The message goes to stderr and reaches Claude.
A net for the obvious, not a sandbox: it prefers letting a command through to blocking a legitimate one (read, grep, ffmpeg).
Tests: tests/test_guard.py (they call check(command) directly).
"""
import json, re, sys

S = r"[^|;&\n]*"                                    # rest of the same command (stops at | ; & and newline)
END = r"(?=$|[\s;|&)'\"`])"                          # end of the argument: "x.mov" yes, "x.mov.txt" no
CMD = r"(?<![\w.-])"                                 # start of a command word (accepts /bin/rm)
MEDIA = r"\.(?:mov|mp4|m4v|mkv|wav|mp3|m4a|aac|webm|mts|aiff?|onnx)" + END
MOV = r"\.mov" + END
PAYLOAD = r"(?:" + MEDIA + r"|(?:^|[\s\"'=/])videos(?:/|" + END + r"))"   # media or the videos/ folder
HOMES = r"(?:~|\$HOME|\$\{HOME\}|/Users/[^/\s]+|/home/[^/\s]+|/root)"           # macOS and Linux home folders
TRASH = r"(?:" + HOMES + r"/(?:\.Trash|\.local/share/Trash)|\$\{?XDG_DATA_HOME\}?/Trash|trash:/)"  # Mac, freedesktop
DISCARD = (r"(?:" + TRASH + r"|(?:/private|/var)?/tmp(?:/|" + END + r")"
           r"|/dev/null|\$\{?TMPDIR\}?|/var/folders/)")
# delete commands, macOS and Linux (trash-cli, GNOME gio, KDE kioclient)
RM = r"(?:rm|unlink|shred|srm|trash(?:-put)?|gio\s+(?:trash|remove)|gvfs-trash|kioclient[56]?\s+(?:del|move))"
GIT_ADD = CMD + r"git(?:\s+(?:-C\s+\S+|-c\s+\S+|--[\w-]+(?:=\S+)?|-[a-zA-Z]+))*\s+(?:add|stage)\b"
HOSTS = ["api.openai.com", "api.groq.com", "api.anthropic.com", "generativelanguage.googleapis.com",
         "api.elevenlabs.io", "api.replicate.com", "api.mistral.ai", "api.together.xyz",
         "speech.googleapis.com", "api.deepgram.com", "api.assemblyai.com"]

MSG_GIT = "Media and models never go into git (the repo is public)."
MSG_MOV = "Don't delete or discard an original recording (.mov). Only after the video is published, and at the author's request."
MSG_UPLOAD = "Don't send audio/video (or videos/) off this computer without an explicit request."
MSG_API = "Transcription and editing are local and free in this project. No paid API without an explicit request."
MSG_HF = ("HyperFrames: only the local render is free (init, lint, snapshot, render, docs, preview). Login, credits, cloud "
          "and HeyGen Pro templates/skills are paid or send things out: only on explicit request.")

RULES = [
    (GIT_ADD + S + r"\s(?:(?-i:-[a-zA-Z]*f[a-zA-Z]*)|--force)" + END, "git add --force overrides .gitignore. " + MSG_GIT),
    (GIT_ADD + S + MEDIA, "Don't add media/models to git (video, audio, .onnx). " + MSG_GIT),
    (CMD + RM + r"\s" + S + MOV, MSG_MOV),
    (CMD + r"mv\s(?=" + S + MOV + r")(?:" + S + r"(?<=\s)[\"']?" + DISCARD + r"[^\s;|&]*\s*(?:$|[;|&\n)`])"  # destination is last
     r"|" + S + r"-t\s*[\"']?" + DISCARD + ")", MSG_MOV),
    (CMD + r"find\s(?=" + S + r"mov\b)(?=" + S + r"(?:(?<=\s)-delete\b|(?<=\s)-exec(?:dir)?\s+\S*(?<![\w.-])(?:" + RM + r"|mv)\b))", MSG_MOV),
    (MOV + r"[^\n]*\|\s*xargs\b" + S + r"\s\S*(?<![\w.-])" + RM + r"\b", MSG_MOV),
    (CMD + r"(?:curl|wget|https?|xh)\s" + S + r"(?:(?-i:(?<=\s)-[FTd]\b)|--form|--data|--upload-file|--post-file)" + S + PAYLOAD, MSG_UPLOAD),
    (CMD + r"(?:curl|wget|https?|xh)\s" + S + r"@\S*" + MEDIA, MSG_UPLOAD),
    (CMD + r"(?:scp|rsync|sftp)\s(?=" + S + PAYLOAD + r")(?=" + S + r"(?:(?<=\s)[\"']?[\w.@-]+:|rsync://))", MSG_UPLOAD),
    (CMD + r"(?:rclone|gsutil|gcloud\s+storage|aws\s+s3(?:api)?|s3cmd|azcopy|b2)\s" + S + PAYLOAD, MSG_UPLOAD),
    (CMD + r"gh\s+(?:release\s+(?:upload|create)|gist\s+create)\s" + S + PAYLOAD, MSG_UPLOAD),
    ("|".join(re.escape(h) for h in HOSTS), MSG_API),
    # HyperFrames: only the local render is free; these commands use a HeyGen account, credits or cloud
    (CMD + r"hyperframes(?:@\S+)?\s+(?:auth|login|billing|cloud|lambda|cloudrun|publish|templates|reverse|catch-up)\b", MSG_HF),
    (CMD + r"hyperframes(?:@\S+)?\s+(?:transcribe|tts|remove-background)\s" + S + r"--engine[=\s]+[\"']?heygen\b", MSG_HF),
    (CMD + r"hyperframes(?:@\S+)?\s+skills\s+update\s+(?:reverse-any-video|style-sampling)\b", MSG_HF),
]

# running a script (not reading it): start of the command, with common prefixes, optionally through python
RUN = (r"^[\s(]*(?:(?:\w+=\S*|time|nohup|exec|env|sudo|uv\s+run|pipx\s+run|(?:ba|z)?sh\s+-c\s+[\"']?)\s*)*"
       r"(?:\S*python[\d.]*\s+(?:-\S+\s+)*)?[\"']?\S*(?<![\w-])")
SCRIPTS = [
    (RUN + r"transcribe\.py\b", r"--engine[=\s]+[\"']?local\b",
     "the third-party skill's transcribe.py only with --engine local (the default 'auto' may send the audio to "
     "Groq/OpenAI). Prefer src/vtk/transcribe_words.py."),
    (RUN + r"upload_parts\.py\b", None, "upload_parts.py sends the video out. " + MSG_UPLOAD),
]


# sfx/*.wav (short effects generated by synthesis, src/vtk/sfx.py) is the only media allowed in git:
# it is removed from the command before the media-in-git rule (the --force rule still applies to it)
SFX = re.compile(r"(?<![\w/.-])(?:\./)?sfx/[\w.*-]+\.wav" + END, re.I)


def check(cmd):
    """Reason for the block (text) or None if the command may run."""
    cmd = cmd or ""
    for i, (rx, msg) in enumerate(RULES):
        target = SFX.sub("sfx/", cmd) if i == 1 else cmd  # RULES[1]: media in git
        if re.search(rx, target, re.I):
            return msg
    for seg in re.split(r"&&|\|\||[;|&\n`]|\$\(", cmd):
        for rx, allow, msg in SCRIPTS:
            if re.search(rx, seg, re.I) and not (allow and re.search(allow, seg, re.I)):
                return msg
    return None


def main():
    try:
        cmd = (json.load(sys.stdin).get("tool_input") or {}).get("command", "") or ""
    except Exception:
        return 0
    msg = check(cmd)
    if msg:
        print(f"BLOCKED by the video-toolkit guard: {msg}\nCommand: {cmd[:200]}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
